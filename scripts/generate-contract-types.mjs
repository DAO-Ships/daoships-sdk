import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { Interface } from 'quais';

const source = await readFile(new URL('../src/abis.ts', import.meta.url), 'utf8');
const CONTRACT_ABIS = JSON.parse(source.split('export const CONTRACT_ABIS = ')[1].split(' as const;')[0]);
function tuple(params, output, event = false) {
  const type = param => event && param.indexed && (['array', 'tuple'].includes(param.baseType) || ['bytes', 'string'].includes(param.type))
    ? 'Indexed' : typeOf(param, output);
  const positional = `readonly [${params.map(type).join(', ')}]`;
  if (!output) return positional;
  const named = params.filter(param => param.name).map(param => `readonly ${JSON.stringify(param.name)}: ${type(param)}`);
  return named.length ? `(${positional} & { ${named.join('; ')} })` : positional;
}
function typeOf(param, output) {
  if (param.baseType === 'array') return `ReadonlyArray<${typeOf(param.arrayChildren, output)}>`;
  if (param.baseType === 'tuple') return tuple(param.components, output);
  if (/^u?int/.test(param.type)) return 'bigint';
  if (param.type === 'bool') return 'boolean';
  if (param.type === 'address' || param.type.startsWith('bytes')) return 'string';
  if (param.type === 'string') return 'string';
  throw new Error(`Unsupported ABI type ${param.type}`);
}
let text = '// Generated by scripts/generate-contract-types.mjs. Integers use bigint; outputs match quais Results.\n'
  + "import type { Indexed } from 'quais';\n"
  + 'export interface ContractMethods {\n';
for (const [name, abi] of Object.entries(CONTRACT_ABIS)) {
  text += `  ${JSON.stringify(name)}: {\n`;
  const funcs = new Interface(abi).fragments.filter(fragment => fragment.type === 'function');
  for (const fn of funcs) {
    const keys = [fn.format('sighash')];
    if (funcs.filter(other => other.name === fn.name).length === 1) keys.push(fn.name);
    const result = fn.outputs.length === 0 ? 'void' : fn.outputs.length === 1 ? typeOf(fn.outputs[0], true) : tuple(fn.outputs, true);
    for (const key of keys) text += `    ${JSON.stringify(key)}: { args: ${tuple(fn.inputs, false)}; result: ${result}; mutability: ${JSON.stringify(fn.stateMutability)} };\n`;
  }
  text += '  };\n';
}
text += '}\n';
text += 'export interface ContractEvents {\n';
for (const [name, abi] of Object.entries(CONTRACT_ABIS)) {
  text += `  ${JSON.stringify(name)}: {\n`;
  const events = new Interface(abi).fragments.filter(fragment => fragment.type === 'event');
  for (const event of events) {
    const keys = [event.format('sighash')];
    if (events.filter(other => other.name === event.name).length === 1) keys.push(event.name);
    for (const key of keys) text += `    ${JSON.stringify(key)}: ${tuple(event.inputs, true, true)};\n`;
  }
  text += '  };\n';
}
text += '}\n';
const target = new URL('../src/contract-types.ts', import.meta.url);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), text, 'Contract type maps are stale; run npm run sync:source.');
else await writeFile(target, text);
